  private findExistingCustomer(input: CustomerInput): CustomerProfile | undefined {
    if (input.email) {
      const byEmail = Array.from(this.customers.values()).find(c => c.email === input.email);
      if (byEmail) return byEmail;
    }

    if (input.phone) {
      const byPhone = Array.from(this.customers.values()).find(c => c.phone === input.phone);
      if (byPhone) return byPhone;
    }

    if (input.externalId) {
      const byExternalId = Array.from(this.customers.values()).find(c => 
        c.externalId === input.externalId
      );
      if (byExternalId) return byExternalId;
    }

    return undefined;
  }

  private updateCustomerActivity(customer: CustomerProfile): void {
    customer.lastInteractionAt = new Date();
    customer.updatedAt = new Date();
    customer.interactionHistory.totalInteractions++;
    customer.interactionHistory.last30Days++;
    customer.interactionHistory.last90Days++;
    this.customers.set(customer.id, customer);
  }

  private determineQueue(input: CreateConversationInput): QueueInfo | undefined {
    if (input.queueId) {
      return this.queues.get(input.queueId);
    }

    const matchingQueue = Array.from(this.queues.values()).find(queue =>
      queue.channels.includes(input.channelType) &&
      queue.isActive &&
      (!queue.departmentFilter || queue.departmentFilter === input.department)
    );

    return matchingQueue;
  }

