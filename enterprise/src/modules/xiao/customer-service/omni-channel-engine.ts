  private async analyzeMessage(message: Message, conversation: Conversation): Promise<MessageAnalysis> {
    const sentimentPromise = this.aiEngine.analyzeSentiment(message.content.text || '');
    const intentPromise = this.aiEngine.detectIntent(message.content.text || '');
    const categoryPromise = this.categorizeMessage(message, conversation);

    const [sentiment, intent, category] = await Promise.all([
      sentimentPromise,
      intentPromise,
      categoryPromise
    ]);

    message.sentiment = sentiment;
    message.intent = intent;
    message.processingInfo.processedBy = 'HYBRID' as any;
    message.processingInfo.processingTime = Date.now() - message.timestamp.getTime();

    return { sentiment, intent, category };
  }

