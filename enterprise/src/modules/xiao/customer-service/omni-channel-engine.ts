  private rankResults(
    conversations: Conversation[],
    query: SearchQuery
  ): Conversation[] {
    return conversations.sort((a, b) => {
      let scoreA = 0;
      let scoreB = 0;

      if (query.text) {
        const lowerQuery = query.text.toLowerCase();
        
        if (a.subject?.toLowerCase().includes(lowerQuery)) scoreA += 10;
        if (b.subject?.toLowerCase().includes(lowerQuery)) scoreB += 10;
        
        if (a.customerInfo.name.toLowerCase().includes(lowerQuery)) scoreA += 5;
        if (b.customerInfo.name.toLowerCase().includes(lowerQuery)) scoreB += 5;
      }

      if (query.priority === 'recency') {
        scoreA += a.updatedAt.getTime() / 1000000000;
        scoreB += b.updatedAt.getTime() / 1000000000;
      }

      return scoreB - scoreA;
    });
  }

