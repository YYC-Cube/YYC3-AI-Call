  private applyFilters(
    conversations: Conversation[],
    filter: Record<string, unknown>
  ): Conversation[] {
    return conversations.filter(conv => {
      for (const [key, value] of Object.entries(filter)) {
        if ((conv as any)[key] !== value) {
          return false;
        }
      }
      return true;
    });
  }

  private applySorting(conversations: Conversation[], sort: any[]): Conversation[] {
    return conversations.sort((a, b) => {
      for (const sortOption of sort) {
        const aValue = (a as any)[sortOption.field];
        const bValue = (b as any)[sortOption.field];
        
        if (aValue < bValue) return sortOption.direction === 'asc' ? -1 : 1;
        if (aValue > bValue) return sortOption.direction === 'asc' ? 1 : -1;
      }
      return 0;
    });
  }

  private fuzzySearch(conversations: Conversation[], query: string): Conversation[] {
    const lowerQuery = query.toLowerCase();
    return conversations.filter(conv =>
      conv.subject?.toLowerCase().includes(lowerQuery) ||
      conv.customerInfo.name.toLowerCase().includes(lowerQuery) ||
      conv.messages.some(m => 
        m.content.text?.toLowerCase().includes(lowerQuery)
      )
    );
  }

  private advancedFilter(
    conversations: Conversation[],
    filters: FilterCondition[]
  ): Conversation[] {
    return conversations.filter(conv =>
      filters.every(filter => {
        const value = (conv as any)[filter.field];
        switch (filter.operator) {
          case 'equals': return value === filter.value;
          case 'contains': return String(value).includes(String(filter.value));
          case 'greater_than': return Number(value) > Number(filter.value);
          case 'less_than': return Number(value) < Number(filter.value);
          default: return true;
        }
      })
    );
  }

