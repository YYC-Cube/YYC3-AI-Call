  private calculateOverallSentiment(data: SentimentDataPoint[]): any {
    if (data.length === 0) {
      return { average: 5, label: 'NEUTRAL' as any };
    }

    const sum = data.reduce((acc, point) => acc + point.score, 0);
    const average = sum / data.length;

    return {
      average,
      label: this.getSentimentLabel(average)
    };
  }

  private getSentimentLabel(score: number): any {
    if (score >= 7) return 'POSITIVE';
    if (score >= 4) return 'NEUTRAL';
    return 'NEGATIVE';
  }

  private calculateTrend(data: SentimentDataPoint[]): any {
    if (data.length < 2) return { direction: 'STABLE' as any, changeRate: 0 };

    const recent = data.slice(-Math.min(5, data.length));
    const older = data.slice(0, Math.max(0, data.length - 5));

    const recentAvg = recent.reduce((acc, p) => acc + p.score, 0) / recent.length;
    const olderAvg = older.length > 0 
      ? older.reduce((acc, p) => acc + p.score, 0) / older.length 
      : recentAvg;

    const changeRate = olderAvg !== 0 ? ((recentAvg - olderAvg) / olderAvg) * 100 : 0;

    let direction: string = 'STABLE';
    if (changeRate > 10) direction = 'IMPROVING';
    else if (changeRate < -10) direction = 'DECLINING';

    return { direction: direction as any, changeRate };
  }

  private identifyKeyMoments(data: SentimentDataPoint[]): any[] {
    const moments: any[] = [];
    
    for (let i = 1; i < data.length - 1; i++) {
      const prev = data[i - 1].score;
      const curr = data[i].score;
      const next = data[i + 1].score;

      const isPeak = curr > prev && curr > next && Math.abs(curr - prev) > 2;
      const isValley = curr < prev && curr < next && Math.abs(curr - prev) > 2;

      if (isPeak || isValley) {
        moments.push({
          timestamp: data[i].timestamp,
          score: curr,
          label: this.getSentimentLabel(curr),
          isExtreme: Math.abs(curr - 5) > 3
        });
      }
    }

    return moments.slice(-5);
  }

